export const findAuthorById = (authorId) => {
  const safeAuthorId = String(authorId || "");
  const existingAuthor = authors.find((author) => author.id === safeAuthorId);

  if (existingAuthor) {
    return existingAuthor;
  }

  return {
    id: safeAuthorId || "unknown",
    name: "Unknown Creator",
    username: "@unknown",
    wallet: "Unavailable",
    followers: 0,
    image: AuthorImage,
  };
};

export const findSeedItemById = (itemId) => {
  const safeItemId = String(itemId || "");
  return items.find((item) => item.id === safeItemId);
};

export const findItemById = (itemId) => findSeedItemById(itemId) || items[0];

export const getAllItems = () => [...items];

export const getItemsForAuthor = (authorId) =>
  items.filter((item) => item.ownerId === authorId);

export const sortItems = (list, sortOrder = "") => {
  const sortableItems = [...list];

  if (sortOrder === "price_low_to_high") {
    sortableItems.sort((left, right) => left.price - right.price);
  }

  if (sortOrder === "price_high_to_low") {
    sortableItems.sort((left, right) => right.price - left.price);
  }

  if (sortOrder === "likes_high_to_low") {
    sortableItems.sort((left, right) => right.likes - left.likes);
  }

  return sortableItems;
};

export const getSortedItems = (sortOrder = "") => sortItems(items, sortOrder);

export const getTopSellers = () => [...authors].sort((left, right) => right.followers - left.followers);